/** One Round 2 race, identified within its group. */
export interface R2RaceRef {
  groupNum: string;
  raceNum: number;
}

/**
 * Round 2 races of a structure in the order they are run. Falls back to one
 * group after another for a team count without a sheet order, and for any
 * race the sheet order does not name.
 */
export function r2RunningOrder(structure: TournamentStructure): R2RaceRef[] {
  const groups = structure.roundTwoGroups ?? [];
  const grouped = groups.flatMap((g) => g.races.map((r) => ({ groupNum: g.groupNum, race: r })));
  const unordered = (a: string, b: string) => [a.toUpperCase(), b.toUpperCase()].sort().join('|');

  // Races per letter pair in group order, consumed as the pair recurs.
  const byPair = new Map<string, typeof grouped>();
  for (const entry of grouped) {
    const key = unordered(entry.race.homeLetter, entry.race.awayLetter);
    byPair.set(key, [...(byPair.get(key) ?? []), entry]);
  }

  const ordered: R2RaceRef[] = [];
  const placed = new Set<(typeof grouped)[number]>();
  for (const [home, away] of R2_RACE_ORDER[structure.teamCount] ?? []) {
    const entry = byPair.get(unordered(home, away))?.find((e) => !placed.has(e));
    if (!entry) continue;
    placed.add(entry);
    ordered.push({ groupNum: entry.groupNum, raceNum: entry.race.raceNum });
  }
  for (const entry of grouped) {
    if (!placed.has(entry)) ordered.push({ groupNum: entry.groupNum, raceNum: entry.race.raceNum });
  }
  return ordered;
}
